    <h2>Origin of the Scheme</h2></div>
 <center>  <div class="container">
        <p>The <strong>TRICHY BISHOP HEBER COLLEGE ALUMNI ASSOCIATION</strong>, registered under the Tamil Nadu Societies Registration Act, 1975 (Tamil Nadu Act 27 of 1975) with Society No: 125 of 2021, facilitates alumni through interactions, financial aid, guidance, collaborative events, project work, internships, and placements. It serves as a bridge between the college and its alumni, fostering pride, commitment, and a sense of belonging while enhancing institutional support.</p>
        <p>The Association mobilizes alumni for the institution's betterment through Alumni Chapters, Association Committees, and individual contacts. It also contributes to the management and recognizes alumni achievements. The <strong>Noon Meal Scheme</strong>, a project under this initiative, aims to improve the nutritional status of marginalized students, ensuring their academic engagement and well-being. Eligible students receive a mess card, allowing them to access meals in the college mess. Alumni support is crucial in providing project opportunities that further empower students, making a meaningful impact on their education and future prospects.</p>
